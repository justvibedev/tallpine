// Generates content/cli-commands.mdx from the real `tallpine` command tree, so the
// full flag reference is checkable instead of hand-copied.
//
//   node scripts/gen-cli-reference.mjs --bin <path-to-tallpine>          # rewrite the page
//   node scripts/gen-cli-reference.mjs --bin <path-to-tallpine> --check  # fail if it is stale
//
// Build the binary from the repo root with `scripts/go build -o /tmp/tallpine ./cmd/tallpine`
// (run inside backend/). Hidden internal commands do not appear in `--help`, so
// they are left out of the page on purpose.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const binIndex = args.indexOf("--bin");
const bin = binIndex >= 0 ? args[binIndex + 1] : process.env.TALLPINE_BIN;
const check = args.includes("--check");
if (!bin) {
  console.error("usage: gen-cli-reference.mjs --bin <path-to-tallpine> [--check]");
  process.exit(2);
}
const outFile = fileURLToPath(new URL("../content/cli-commands.mdx", import.meta.url));

function help(path) {
  // A scratch HOME and an empty environment keep the output independent of the machine.
  const env = { PATH: process.env.PATH ?? "", HOME: "/tmp/tallpine-docs-gen", NO_COLOR: "1" };
  return execFileSync(bin, [...path, "--help"], { env, encoding: "utf8" }).replace(/\s+$/, "");
}

function subcommands(text) {
  const match = text.match(/\nAvailable Commands:\n([\s\S]*?)(?:\n\n|$)/);
  if (!match) return [];
  return match[1]
    .split("\n")
    .map((line) => line.match(/^ {2}(\S+)/)?.[1])
    .filter((name) => name && name !== "help" && name !== "completion");
}

// Drops the trailing "Use ... for more information" line and the empty-handed
// `-h, --help` flag so the page shows only what a person would act on.
function clean(text) {
  return text
    .replace(/\n\nUse "tallpine[^\n]*--help" for more information about a command\./, "")
    .replace(/\n {2}-h, --help {3,}help for [^\n]*/g, "")
    .replace(/\n\nFlags:\s*$/, "")
    .trimEnd();
}

const sections = [];
function walk(path, depth) {
  const text = help(path);
  const heading = "#".repeat(Math.min(depth + 2, 6));
  sections.push(`${heading} \`${["tallpine", ...path].join(" ")}\`\n\n\`\`\`text\n${clean(text)}\n\`\`\`\n`);
  for (const name of subcommands(text)) walk([...path, name], depth + 1);
}

const top = help([]);
for (const name of subcommands(top)) walk([name], 0);

const page = `---
title: Command reference
description: Every public tallpine command with its flags, generated from the CLI.
---

{/* Generated by scripts/gen-cli-reference.mjs from \`tallpine --help\`. Do not edit by hand. */}

This page is the complete, generated list of public \`tallpine\` commands and flags. For explanations and examples, see the [CLI reference](/cli). Internal commands such as \`daemon\`, \`hooks\`, \`launch\`, \`agent-process\`, \`pty-host\`, \`chat-host\`, \`mcp\`, \`git-credential\`, and \`gh-exec\` are not listed.

${sections.join("\n")}`;

if (check) {
  const current = readFileSync(outFile, "utf8");
  if (current !== page) {
    console.error("content/cli-commands.mdx is stale. Re-run scripts/gen-cli-reference.mjs without --check.");
    process.exit(1);
  }
  console.log("content/cli-commands.mdx is up to date.");
} else {
  writeFileSync(outFile, page);
  console.log(`Wrote ${outFile} (${sections.length} commands).`);
}
