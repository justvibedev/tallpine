package gitworktree

import (
	"context"
	"errors"
	"os"
	"path/filepath"
	"testing"

	"tallpine.eu/tallpine/backend/internal/ports"
)

// Workers symlink node_modules from a sibling worktree. A directory-only
// ignore pattern does not match a symlink, so git reports it untracked; it
// must not make the worktree look dirty, while real untracked work still does.
func TestDestroyIgnoresNodeModulesSymlink(t *testing.T) {
	t.Parallel()

	_, tmp, _, _, ws := newOriginWorkspace(t)
	ctx := context.Background()
	info, err := ws.Create(ctx, ports.WorkspaceConfig{ProjectID: "proj", SessionID: "sess", Branch: "feature/nm"})
	if err != nil {
		t.Fatalf("create: %v", err)
	}
	target := filepath.Join(tmp, "other", "node_modules")
	if err := os.MkdirAll(target, 0o750); err != nil {
		t.Fatalf("mkdir target: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(info.Path, "frontend"), 0o750); err != nil {
		t.Fatalf("mkdir frontend: %v", err)
	}
	for _, link := range []string{"node_modules", filepath.Join("frontend", "node_modules")} {
		if err := os.Symlink(target, filepath.Join(info.Path, link)); err != nil {
			t.Fatalf("symlink: %v", err)
		}
	}
	dirty, err := ws.isDirty(ctx, info.Path)
	if err != nil || dirty {
		t.Fatalf("isDirty with only node_modules symlinks = %v, %v; want false, nil", dirty, err)
	}

	if err := os.WriteFile(filepath.Join(info.Path, "wip.txt"), []byte("work"), 0o600); err != nil {
		t.Fatalf("write wip: %v", err)
	}
	err = ws.Destroy(ctx, info)
	if !errors.Is(err, ports.ErrWorkspaceDirty) {
		t.Fatalf("destroy error = %v, want ports.ErrWorkspaceDirty", err)
	}

	if err := os.Remove(filepath.Join(info.Path, "wip.txt")); err != nil {
		t.Fatalf("remove wip: %v", err)
	}
	if err := ws.Destroy(ctx, info); err != nil {
		t.Fatalf("destroy with only symlinks: %v", err)
	}
}
